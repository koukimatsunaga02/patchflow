const {boot,shared,assert}=require('./test-av-ui.cjs');
shared.clear();const app=boot('audio'),doc=app.document;
assert.equal(doc.querySelectorAll('#catalog img').length,0,'closed startup does not request library photos');
assert.ok(doc.querySelectorAll('#nodes img').length>0,'canvas equipment remains immediately available');
assert.equal(doc.querySelector('#nodes img').hasAttribute('loading'),false,'canvas photo load timing is unchanged');
app.run("setDrawer('library',true)");
assert.equal(doc.querySelectorAll('#catalog [data-add]').length,98);
for(const image of doc.querySelectorAll('#catalog img')){assert.equal(image.getAttribute('loading'),'lazy');assert.equal(image.getAttribute('decoding'),'async')}
const original=doc.querySelector('#catalog [data-add]');
app.run("catalog();setMediaLayer('video',false)");app.flush();
assert.equal(doc.querySelector('#catalog [data-add]'),original,'unrelated canvas changes preserve library cards');
app.run("setDrawer('library',false)");app.change('#categoryfilter','microphone');
assert.equal(doc.querySelector('#catalog [data-add]'),original,'closed library defers filter work');
app.run("setDrawer('library',true)");
assert.equal(doc.querySelectorAll('#catalog [data-add]').length,7,'reopening applies the latest filters');
app.change('#brandfilter','RØDE');assert.equal(doc.querySelectorAll('#catalog [data-add]').length,4);
app.click('[data-catalog-view="table"]');
assert.equal(doc.querySelectorAll('.catalog-table [data-add]').length,4);
assert.equal(doc.querySelector('.catalog-table img').getAttribute('loading'),'lazy');
const row=doc.querySelector('.catalog-table [data-add]'),before=app.run('state.nodes.length');
const key=new app.ctx.window.Event('keydown',{cancelable:true});key.key='Enter';row.onkeydown(key);app.flush();
assert.equal(app.run('state.nodes.length'),before+1,'keyboard add works after deferred table rendering');
assert.equal(typeof row.onpointerdown,'function','drag handler is retained');
app.click('[data-catalog-view="grid"]');app.change('#categoryfilter','all');app.change('#brandfilter','all');
doc.querySelector('#search').value='UMC202HD';doc.querySelector('#search').dispatchEvent(new app.ctx.window.Event('input'));
assert.equal(doc.querySelectorAll('#catalog [data-add]').length,1);
app.click('[data-add="umc202hd"]');assert.equal(app.run('state.nodes.at(-1).model'),'umc202hd');
assert.equal(app.run('validate(state)===state'),true);
console.log('PASS: deferred closed catalog, lazy photos, stable unchanged cards, reopen filters, grid/table, search, keyboard and click add');
